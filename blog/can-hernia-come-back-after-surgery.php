                            <p class="text-slate-600 text-sm leading-relaxed">
                                Severe, chronic coughing during the first few weeks after surgery can put strain on the fresh repair. If you need to cough or sneeze, it is recommended to support your abdomen by pressing a pillow gently against your incisions to splint the area and absorb the pressure.
                            </p>
                        </div>

                        <div class="faq-item bg-slate-50 rounded-2xl p-6 border border-slate-200/50">
                            <h4 class="font-bold text-slate-900 mb-2">How can I tell if my hernia has recurred or if it is just scar tissue?</h4>
                            <p class="text-slate-655 text-sm leading-relaxed">
                                Scar tissue or postoperative fluid (seromas) can cause a firm sensation or mild bulge that typically resolves or softens over 6-12 weeks. A true recurrence will usually present as a soft, reducible bulge that grows when coughing or straining and may disappear when lying down. A surgeon can confirm this using a physical examination or an ultrasound.
                            </p>
