                            <p class="text-slate-600 text-sm leading-relaxed">
                                While a second repair is surgically more complex due to scar tissue, it is very safe when performed by an experienced hernia specialist. Using minimally invasive approaches (laparoscopic or robotic) allows the surgeon to access the hernia from a different tissue plane, avoiding the scar tissue from your first operation.
                            </p>
