                                <strong class="text-slate-900 block">Umbilical Hernia (Navel)</strong>
                                <span class="text-slate-600 text-sm">Occurs right at or very close to the belly button. It is common in infants (often resolving on its own) but can also develop in adults due to pressure from obesity, multiple pregnancies, or fluid accumulation in the abdomen.</span>
                            </div>
                        </li>
