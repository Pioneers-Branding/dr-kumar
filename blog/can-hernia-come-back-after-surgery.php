                                <strong class="text-slate-900 block">Inguinal Hernia (Groin)</strong>
                                <span class="text-slate-600 text-sm">Occurs in the groin area when a loop of intestine or fat pushes into the inguinal canal. This is the most common type of hernia, particularly in men, accounting for roughly 75% of all abdominal wall hernias.</span>
                            </div>
                        </li>
