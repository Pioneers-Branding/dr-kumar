                                <span class="text-slate-600 text-sm">Develops at the site of a previous surgical scar. If the surgical wound from a past abdominal operation does not heal perfectly, the muscle wall can separate, allowing a hernia to bulge through. These hernias carry the highest rate of recurrence.</span>
                            </div>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-2.5 h-2.5 rounded-full bg-brand-600 mt-2 shrink-0"></span>
