                                <strong class="text-slate-900 block">Ventral Hernia</strong>
                                <span class="text-slate-600 text-sm">A general term for any hernia occurring along the midline of the abdomen (excluding umbilical hernias). This includes epigastric hernias (above the navel) and spigelian hernias.</span>
                            </div>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-2.5 h-2.5 rounded-full bg-brand-600 mt-2 shrink-0"></span>
                            <div>
                                <strong class="text-slate-900 block">Femoral Hernia</strong>
                                <span class="text-slate-600 text-sm">A less common type of groin hernia that develops slightly lower than an inguinal hernia, in the femoral canal. It is more common in women and carries a high risk of strangulation (obstruction of blood supply).</span>
                            </div>
                        </li>
                    </ul>

                    <!-- Why do hernias come back? -->
                    <h2 class="font-display text-2xl font-bold text-slate-900 mt-10 mb-4 border-b border-slate-100 pb-2">Why do hernias come back?</h2>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        Understanding the physiological and clinical factors of recurrence is key to prevention. If you ask yourself, "<strong>after hernia surgery can it come back</strong>?" the answer depends on several intersecting variables:
                    </p>
                    
                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">A. Tissue Tension and Weakness</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        In the past, surgeons performed "tension repairs" where the torn muscle layers were pulled together and stitched shut. Because the surrounding muscle was already thin or weak, pulling it under tension often caused the sutures to rip through the tissue over time. This tissue failure is the classic cause of recurrence. Today, the use of synthetic mesh provides a tension-free repair, which has dramatically lowered failure rates.
                    </p>
                    
                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">B. Improper Mesh Selection or Placement</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        If the surgical mesh selected is too small, it may not overlap the borders of the muscle tear sufficiently. Over time, tissue pressure can cause the mesh to wrinkle, shrink, or shift, allowing the hernia to bulge out around the edge of the mesh. Precise placement (such as retro-rectus or preperitoneal placement) is critical to prevent shifting.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">C. Surgical Site Infection</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        An infection in the surgical wound after the initial operation can compromise the body's natural healing process. If infection sets in, it can weaken the scar tissue or prevent the surrounding muscles from incorporating the mesh, leading to a breakdown of the repair.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">D. Chronic Abdominal Straining</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        Any condition that chronically increases pressure inside your abdomen can place continuous force on the surgical repair. Persistent coughing (common in smokers or COPD patients), severe constipation (straining during bowel movements), urinary obstruction (due to an enlarged prostate), or premature return to heavy weightlifting can stress the surgical site before tissue integration is complete.
                    </p>

