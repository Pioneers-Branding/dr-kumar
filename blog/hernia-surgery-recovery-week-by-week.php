                            <span class="text-slate-700 text-sm md:text-base">A fever above 101°F (38.3°C).</span>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-5 h-5 rounded-full bg-red-100 text-red-700 flex items-center justify-center shrink-0 mt-0.5 text-xs font-bold font-sans">!</span>
                            <span class="text-slate-700 text-sm md:text-base">Spreading redness, increasing heat, or foul-smelling drainage around the incision site.</span>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-5 h-5 rounded-full bg-red-100 text-red-700 flex items-center justify-center shrink-0 mt-0.5 text-xs font-bold font-sans">!</span>
                            <span class="text-slate-700 text-sm md:text-base">Sudden, severe pain that your prescribed medication cannot control.</span>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-5 h-5 rounded-full bg-red-100 text-red-700 flex items-center justify-center shrink-0 mt-0.5 text-xs font-bold font-sans">!</span>
                            <span class="text-slate-700 text-sm md:text-base">Persistent nausea or an inability to keep fluids down.</span>
