                    </p>

                    <!-- What is Hernia Surgery? -->
                    <h2 class="font-display text-2xl font-bold text-slate-900 mt-10 mb-4 border-b border-slate-100 pb-2">What is Hernia Surgery?</h2>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        Hernia surgery is a procedure performed to repair a mechanical gap in the abdominal muscle wall. During the operation, the surgeon gently pushes the bulging internal tissues (such as fat or loops of intestine) back into their correct anatomical position. The gap in the muscle is then closed and usually reinforced with a medical-grade mesh to prevent the hernia from returning.
                    </p>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        This repair can be performed using two main approaches:
                    </p>
                    <ul class="list-disc list-inside text-slate-600 space-y-2 mb-6 pl-4">
                        <li><strong>Open Surgery:</strong> The surgeon makes a single incision over the hernia site to repair the muscle layer directly.</li>
                        <li><strong>Minimally Invasive Surgery (Laparoscopic or Robotic):</strong> The surgeon makes several tiny keyhole incisions, inserts a camera, and uses specialized instruments to perform the repair from behind the muscle wall.</li>
                    </ul>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        Regardless of the method used, the surgical team must manipulate muscle tissue, fascia, and surrounding blood vessels. This internal manipulation triggers your body's natural healing response, leading to temporary postoperative changes.
                    </p>

                    <!-- Reasons Why Your Stomach Is Bigger After Hernia Surgery -->
                    <h2 class="font-display text-2xl font-bold text-slate-900 mt-10 mb-4 border-b border-slate-100 pb-2">Reasons Why Your Stomach Is Bigger After Hernia Surgery</h2>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        If your <strong>stomach swollen after hernia surgery</strong> is causing concern, it helps to understand the physical and physiological factors behind this expansion. Here are the primary reasons:
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">1. Gas Inflation (Carbon Dioxide)</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        During laparoscopic or robotic-assisted hernia repairs, the surgical team inflates your abdominal cavity with carbon dioxide (CO2) gas. This gas expansion lifts the abdominal wall, creating a clear working space for the camera and instruments. Although the surgeon releases most of the gas at the end of the procedure, small pockets remain trapped. This trapped gas bloats your abdomen, causing a noticeable distension and often leading to referred pain in the shoulders.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">2. Fluid Accumulation (Seroma and Hematoma)</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        When a hernia is repaired, it leaves behind an empty space where the bulging tissue used to sit. Your body naturally fills this "dead space" with inflammatory fluids. If clear fluid fills the space, it forms a <strong>seroma</strong>. If blood pools there, it is a <strong>hematoma</strong>. These fluid collections can feel firm and resemble the original hernia bulge, causing the stomach to look bigger.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">3. Local Inflammatory Healing Response</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        Any tissue trauma, including incision cuts, muscle dissection, and placing surgical mesh, triggers an acute inflammatory response. Blood vessels dilate, sending white blood cells, oxygen, and fluid to the site to start the healing process. This localized swelling is your body's natural way of repairing itself.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">4. Muscle Relaxation and Nerve Blocks</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        Anesthesia and local nerve blocks (such as TAP blocks used to manage post-op pain) temporarily paralyze or relax your abdominal wall muscles. Without their normal muscular tone, the abdominal walls relax and sag outward, making your stomach look larger than usual.
                    </p>

                    <h3 class="font-bold text-slate-900 text-lg mt-6 mb-3">5. Post-Operative Constipation</h3>
                    <p class="text-slate-600 leading-relaxed mb-4">
                        Pain medications (especially opioids), lack of mobility, and dehydration slow down your digestive system after surgery. This leads to constipation and gas buildup in your intestines, which causes significant lower stomach bloating.
                    </p>

