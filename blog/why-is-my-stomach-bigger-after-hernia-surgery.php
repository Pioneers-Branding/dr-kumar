                                <strong class="text-slate-900 block">Weeks 2–3: Gradual Improvement</strong>
                                <span class="text-slate-600 text-sm">The trapped carbon dioxide gas is fully absorbed by the body. Constipation resolves as you return to normal diet and activity, and muscle tone begins to recover.</span>
                            </div>
                        </li>
                        <li class="flex items-start gap-3">
                            <span class="w-2.5 h-2.5 rounded-full bg-brand-600 mt-2 shrink-0"></span>
