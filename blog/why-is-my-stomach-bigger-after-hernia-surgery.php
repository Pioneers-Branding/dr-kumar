                            <li><strong>Apply Ice Packs:</strong> Apply ice wrapped in a cloth to the swollen area for 15-20 minutes at a time during the first 48-72 hours to reduce blood flow and inflammation.</li>
                            <li><strong>Walk Regularly:</strong> Take short, gentle walks around your home. Walking is the best way to stimulate bowel motility, release trapped gas, and prevent constipation.</li>
                            <li><strong>Eat High-Fiber Foods:</strong> Focus on fresh fruits, vegetables, and whole grains to support digestion. Avoid carbonated drinks and gas-producing foods (beans, cabbage).</li>
                            <li><strong>Stay Hydrated:</strong> Drink plenty of water to help flush out inflammatory waste and prevent bowel straining.</li>
                            <li><strong>Avoid Straining:</strong> Never strain during bowel movements; use stool softeners as advised by your healthcare team.</li>
                        </ul>
