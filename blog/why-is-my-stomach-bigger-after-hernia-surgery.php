                        Undergoing a hernia repair is a positive step toward resolving pain and protecting your abdominal organs. During recovery, you expect to feel some soreness and see a few bandages. However, many patients are surprised and concerned when they look in the mirror and ask: <strong>why is my stomach bigger after hernia surgery</strong>?
