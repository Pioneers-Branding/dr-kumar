                    </ul>

                    <!-- Signs That Your Swelling Is Normal -->
                    <h2 class="font-display text-2xl font-bold text-slate-900 mt-10 mb-4 border-b border-slate-100 pb-2">Signs That Your Swelling Is Normal</h2>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        It is normal to feel anxious about changes in your body after surgery. Here are indicators that your stomach swelling is a healthy part of the recovery process:
                    </p>
                    <ul class="list-disc list-inside text-slate-600 space-y-2 mb-8 pl-4">
                        <li>The swollen area is soft or slightly firm, but not rock-hard.</li>
                        <li>The bloating is spread evenly across your abdomen rather than concentrated in a hot, red lump.</li>
                        <li>Your pain levels are gradually improving day by day and respond well to prescribed pain medication.</li>
                        <li>You are able to pass gas and have normal bowel movements.</li>
                        <li>You do not have a high fever or chills.</li>
                    </ul>

                    <!-- Signs That Require Medical Attention -->
                    <h2 class="font-display text-2xl font-bold text-slate-900 mt-10 mb-4 border-b border-slate-100 pb-2">Signs That Req&#117;ire Medical Attention</h2>
                    <p class="text-slate-600 leading-relaxed mb-6">
                        While swelling is expected, certain symptoms indicate a post-operative complication (such as a severe infection, hematoma, or bowel obstruction) that needs prompt medical evaluation:
                    </p>
                    <ul class="list-disc list-inside text-slate-655 space-y-2 mb-8 pl-4">
                        <li>A sudden, rapid increase in swelling at the incision site.</li>
                        <li>The swollen area becomes extremely hard, hot to the touch, or severely painful.</li>
                        <li>Redness spreading outward from the incisions, or pus/cloudy fluid draining from the wounds.</li>
                        <li>A body temperature rising above 101°F (38.3°C).</li>
                        <li>Persistent nausea, vomiting, or an inability to keep fluids down.</li>
                        <li>Inability to pass gas or have a bowel movement for more than 3-4 days post-surgery.</li>
                    </ul>

